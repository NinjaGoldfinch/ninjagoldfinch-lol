mode=run

usage() {
  cat <<USAGE
usage: $0 --ssh-keys FILE [options]

  --ssh-keys FILE      public keys allowed to log in to the VM (required)
  --vmid N             VM id (default: the cluster's next free id)
  --name NAME          VM name (default: $name)
  --storage ID         disk + cloud-init drive storage (default: $storage)
  --snippets ID        storage with the 'snippets' content type (default: $snippets)
  --bridge BRIDGE      network bridge (default: $bridge)
  --cores N            (default: $cores)
  --memory MB          (default: $memory)
  --disk SIZE          root disk size (default: $disk)
  --ip CIDR|dhcp       static address like 192.168.68.51/22, or dhcp (default)
  --gw ADDR            gateway, with a static --ip
  --user NAME          VM login user (default: $ciuser)
  --image-dir DIR      where the Debian image is cached (default: $image_dir)
  --dry-run            print the qm commands instead of running them
  --print-vendor-data  print the cloud-init vendor-data and exit
USAGE
}

die() { echo "create-vm: $*" >&2; exit 1; }

while [ $# -gt 0 ]; do
  case "$1" in
    --ssh-keys) ssh_keys=$2; shift ;;
    --vmid) vmid=$2; shift ;;
    --name) name=$2; shift ;;
    --storage) storage=$2; shift ;;
    --snippets) snippets=$2; shift ;;
    --bridge) bridge=$2; shift ;;
    --cores) cores=$2; shift ;;
    --memory) memory=$2; shift ;;
    --disk) disk=$2; shift ;;
    --ip) ip=$2; shift ;;
    --gw) gw=$2; shift ;;
    --user) ciuser=$2; shift ;;
    --image-dir) image_dir=$2; shift ;;
    --dry-run) mode=dry ;;
    --print-vendor-data) mode=vendor ;;
    -h|--help) usage; exit 0 ;;
    *) usage >&2; die "unknown option: $1" ;;
  esac
  shift
done

[[ $ciuser =~ ^[a-z_][a-z0-9_-]*$ ]] || die "--user must be a plain login name"
[[ $name =~ ^[A-Za-z0-9][A-Za-z0-9.-]*$ ]] || die "--name must be a DNS name"
[ -r "$here/ninjagoldfinch-update" ] || die "ninjagoldfinch-update must sit next to this script"

# Cloud-init vendor-data. Files go in as base64 so their contents can't break the YAML.
vendor_data() {
  cat <<VENDOR
#cloud-config
# Generated by deploy/proxmox/create-vm.sh.
package_update: true
package_upgrade: true
packages: [qemu-guest-agent, docker.io, docker-compose, git, unattended-upgrades]
write_files:
  - path: /usr/local/bin/ninjagoldfinch-update
    permissions: "0755"
    encoding: b64
    content: $(base64 -w0 < "$here/ninjagoldfinch-update")
  - path: /etc/ssh/ssh_known_hosts
    append: true
    encoding: b64
    content: $(printf '%s\n' "$GITHUB_HOST_KEYS" | base64 -w0)
runcmd:
  - [install, -d, -o, "$ciuser", -g, "$ciuser", /opt/ninjagoldfinch]
  - [usermod, -aG, docker, "$ciuser"]
  - [su, -, "$ciuser", -c, "install -d -m 700 ~/.ssh && { test -f ~/.ssh/ninjagoldfinch-deploy || ssh-keygen -q -t ed25519 -N '' -C ninjagoldfinch-deploy@$name -f ~/.ssh/ninjagoldfinch-deploy; }"]
  - [systemctl, enable, --now, qemu-guest-agent, docker]
VENDOR
}

if [ "$mode" = vendor ]; then
  vendor_data
  exit 0
fi

[ -n "$ssh_keys" ] || { usage >&2; die "--ssh-keys is required"; }
[ -r "$ssh_keys" ] || die "can't read $ssh_keys"
if [ "$ip" = dhcp ]; then
  ipconfig="ip=dhcp"
else
  [ -n "$gw" ] || die "a static --ip needs --gw"
  ipconfig="ip=$ip,gw=$gw"
fi

step() { [ "$mode" = dry ] || echo "create-vm: $*" >&2; }
run() { if [ "$mode" = dry ]; then printf '%q ' "$@"; echo; else "$@"; fi; }
if [ -t 2 ]; then curl_progress=--progress-bar; else curl_progress=--silent; fi

if [ "$mode" = run ]; then
  [ "$(id -u)" = 0 ] || die "run as root on the Proxmox host"
  command -v qm >/dev/null || die "qm not found; this must run on a Proxmox VE host"
  pvesm status --content snippets 2>/dev/null | awk 'NR>1{print $1}' | grep -qx "$snippets" \
    || die "storage '$snippets' has no 'snippets' content type; add it (Datacenter → Storage → $snippets → Content) or pass --snippets"
fi

[ -n "$vmid" ] || vmid=$(if [ "$mode" = dry ]; then echo 9000; else pvesh get /cluster/nextid; fi)
[[ $vmid =~ ^[0-9]+$ ]] || die "--vmid must be a number"
snippet="$name-$vmid.yaml"
image="$image_dir/$(basename "$IMAGE_URL")"

# Download (or refresh) the Debian cloud image and check it against Debian's SHA512SUMS.
run mkdir -p "$image_dir"
if [ -f "$image" ]; then
  step "refreshing $image if Debian has a newer one"
  run curl -fSL "$curl_progress" -z "$image" -o "$image" "$IMAGE_URL"
else
  step "downloading the Debian 13 cloud image (~400 MB) to $image"
  run curl -fSL "$curl_progress" -o "$image" "$IMAGE_URL"
fi
if [ "$mode" = run ]; then
  step "checking it against Debian's SHA512SUMS"
  sum=$(curl -fsSL "$SUMS_URL" | awk -v f="$(basename "$IMAGE_URL")" '$2==f{print $1}')
  [ -n "$sum" ] || die "no checksum for $(basename "$IMAGE_URL") in $SUMS_URL"
  echo "$sum  $image" | sha512sum -c --quiet - || die "checksum mismatch for $image; delete it and retry"
  snippet_path=$(pvesm path "$snippets:snippets/$snippet")
  vendor_data > "$snippet_path"
  echo "create-vm: wrote $snippet_path"
else
  echo "# vendor-data → $snippets:snippets/$snippet (see --print-vendor-data)"
fi

step "creating VM $vmid ($name)"
run qm create "$vmid" --name "$name" --ostype l26 --cpu host --cores "$cores" --memory "$memory" \
  --net0 "virtio,bridge=$bridge" --scsihw virtio-scsi-single --agent enabled=1 \
  --serial0 socket --vga serial0
run qm set "$vmid" --scsi0 "$storage:0,import-from=$image,discard=on,ssd=1"
run qm resize "$vmid" scsi0 "$disk"
run qm set "$vmid" --ide2 "$storage:cloudinit" --boot order=scsi0
run qm set "$vmid" --ciuser "$ciuser" --sshkeys "$ssh_keys" --ipconfig0 "$ipconfig" \
  --cicustom "vendor=$snippets:snippets/$snippet"
step "starting VM $vmid"
run qm start "$vmid"

if [ "$ip" = dhcp ]; then
  addr="<vm-ip>"
  find_ip="qm guest cmd $vmid network-get-interfaces | grep -o '\"ip-address\" : \"[0-9.]*\"' | grep -v 127.0.0.1
                         (once the guest agent is up, ~1-2 min)"
else
  addr=${ip%/*}
  find_ip="$addr"
fi

cat <<NEXT
create-vm: VM $vmid ($name) created and booting. First boot installs Docker; give it a few minutes.
Next:
  1. Its address:       $find_ip
  2. Log in:            ssh $ciuser@$addr
  3. Deploy key:        cat ~/.ssh/ninjagoldfinch-deploy.pub
                        add it read-only: GitHub → NinjaGoldfinch/ninjagoldfinch-lol → Settings → Deploy keys
  4. First deploy:      ninjagoldfinch-update        (clones, creates /opt/ninjagoldfinch/deploy/.env, stops)
                        edit /opt/ninjagoldfinch/deploy/.env (PROXY_KEY), then ninjagoldfinch-update again
  5. Open               http://$addr:3000
NEXT
