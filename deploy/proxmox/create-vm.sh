# Create a Debian 13 VM on a Proxmox VE host that builds and runs
# ninjagoldfinch-lol in Docker. Adapted from riot-proxy's deploy/proxmox.
# Run as root on the host, next to ninjagoldfinch-update. See README.md here.
#
# Proxmox's own cloud-init sets the user, SSH keys and network; a vendor-data
# snippet installs Docker and git, pins GitHub's SSH host keys, creates a
# read-only deploy key for the user and installs ninjagoldfinch-update.
set -euo pipefail

